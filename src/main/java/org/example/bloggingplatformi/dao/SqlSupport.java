package org.example.bloggingplatformi.dao;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.OffsetDateTime;

import org.example.bloggingplatformi.exception.DataAccessException;
import org.example.bloggingplatformi.exception.DuplicateEntityException;

/**
 * Shared JDBC plumbing: null-safe column reads, generated-key retrieval and
 * SQLSTATE translation.
 *
 * <p>Nothing here builds SQL from input. Every statement in this package is a
 * {@link PreparedStatement} with bound parameters; the only strings ever
 * concatenated into a query are compile-time constants, such as the ORDER BY
 * fragments held by {@link org.example.bloggingplatformi.model.PostSort}.
 */
final class SqlSupport {

    /** unique_violation: a UNIQUE constraint rejected the write. */
    static final String SQLSTATE_UNIQUE_VIOLATION = "23505";

    /** foreign_key_violation: the referenced row does not exist. */
    static final String SQLSTATE_FOREIGN_KEY_VIOLATION = "23503";

    /** check_violation: a CHECK constraint rejected the value. */
    static final String SQLSTATE_CHECK_VIOLATION = "23514";

    /** not_null_violation. */
    static final String SQLSTATE_NOT_NULL_VIOLATION = "23502";

    private SqlSupport() {
    }

    // -----------------------------------------------------------------
    // Null-safe reads
    //
    // ResultSet.getLong returns 0 for SQL NULL and getInt returns 0 too, so a
    // genuine zero and a missing value are indistinguishable unless wasNull()
    // is consulted immediately afterwards.
    // -----------------------------------------------------------------

    static Long getNullableLong(ResultSet rs, String column) throws SQLException {
        long value = rs.getLong(column);
        return rs.wasNull() ? null : value;
    }

    static Integer getNullableInt(ResultSet rs, String column) throws SQLException {
        int value = rs.getInt(column);
        return rs.wasNull() ? null : value;
    }

    /**
     * Reads a {@code TIMESTAMPTZ}.
     *
     * <p>Requested as {@link OffsetDateTime} rather than {@code Timestamp}:
     * the latter has no zone, so the driver would convert to the JVM default
     * and the offset the column was storing would be lost.
     */
    static OffsetDateTime getOffsetDateTime(ResultSet rs, String column) throws SQLException {
        return rs.getObject(column, OffsetDateTime.class);
    }

    // -----------------------------------------------------------------
    // Writes
    // -----------------------------------------------------------------

    /** Binds a possibly-null Long without the caller writing the branch each time. */
    static void setNullableLong(PreparedStatement ps, int index, Long value) throws SQLException {
        if (value == null) {
            ps.setNull(index, java.sql.Types.BIGINT);
        } else {
            ps.setLong(index, value);
        }
    }

    static void setNullableInt(PreparedStatement ps, int index, Integer value) throws SQLException {
        if (value == null) {
            ps.setNull(index, java.sql.Types.INTEGER);
        } else {
            ps.setInt(index, value);
        }
    }

    static void setNullableTimestamp(PreparedStatement ps, int index, OffsetDateTime value)
            throws SQLException {
        if (value == null) {
            ps.setNull(index, java.sql.Types.TIMESTAMP_WITH_TIMEZONE);
        } else {
            ps.setObject(index, value);
        }
    }

    /**
     * Returns the key generated by the statement just executed.
     *
     * @throws DataAccessException if the insert produced no key, which means
     *         the statement was not created with {@link Statement#RETURN_GENERATED_KEYS}
     */
    static long generatedKey(PreparedStatement ps) throws SQLException {
        try (ResultSet keys = ps.getGeneratedKeys()) {
            if (keys.next()) {
                return keys.getLong(1);
            }
        }
        throw new DataAccessException("Insert succeeded but returned no generated key");
    }

    // -----------------------------------------------------------------
    // Error translation
    // -----------------------------------------------------------------

    /**
     * Turns a constraint violation into the exception the UI can act on.
     *
     * <p>The constraint name carries the meaning, which is why every
     * constraint in {@code V1__schema.sql} is named explicitly instead of
     * being left to PostgreSQL's generated names.
     */
    static RuntimeException translate(SQLException e, String entity) {
        if (SQLSTATE_UNIQUE_VIOLATION.equals(e.getSQLState())) {
            String field = fieldFromConstraint(e.getMessage());
            return new DuplicateEntityException(field,
                    "That " + field + " is already in use.", e);
        }
        if (SQLSTATE_FOREIGN_KEY_VIOLATION.equals(e.getSQLState())) {
            return new DataAccessException(
                    "Referenced record does not exist, or is still referenced elsewhere: "
                    + e.getMessage(), e);
        }
        if (SQLSTATE_CHECK_VIOLATION.equals(e.getSQLState())
                || SQLSTATE_NOT_NULL_VIOLATION.equals(e.getSQLState())) {
            return new DataAccessException(
                    "The value rejected by the database was invalid: " + e.getMessage(), e);
        }
        return new DataAccessException(
                entity + " operation failed [SQLSTATE " + e.getSQLState() + "]: " + e.getMessage(), e);
    }

    /** Maps a named constraint back to the field a user would recognise. */
    private static String fieldFromConstraint(String message) {
        if (message == null) {
            return "value";
        }
        String lower = message.toLowerCase();
        if (lower.contains("uq_users_username")) {
            return "username";
        }
        if (lower.contains("uq_users_email")) {
            return "email";
        }
        if (lower.contains("uq_posts_slug")) {
            return "slug";
        }
        if (lower.contains("uq_tags_name") || lower.contains("uq_tags_slug")) {
            return "tag name";
        }
        if (lower.contains("uq_reviews_post_reviewer")) {
            return "review";
        }
        if (lower.contains("pk_post_tags")) {
            return "tag assignment";
        }
        return "value";
    }

    /** Closes a connection only when this code opened it. */
    static void closeIfOwned(Connection connection, boolean owned) {
        if (owned && connection != null) {
            try {
                connection.close();
            } catch (SQLException ignored) {
                // The pool handles a connection that cannot be returned.
            }
        }
    }
}
